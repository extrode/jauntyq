using JauntyQ.Schema;
using JauntyQ.SqlParser.IR;

namespace JauntyQ.Generator;

public static class CodeEmitter
{
    public static string Emit(QueryModel query, ProjectionModel projection, string originalSql, string entityName, DatabaseSchema? schema = null, Directives.DirectiveModel? directives = null)
    {
        var sb = new System.Text.StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        sb.AppendLine("namespace JauntyQ.Generated");
        sb.AppendLine("{");

        // Entity partial class containing nested Result class and query methods
        sb.AppendLine($"    public partial class {entityName}");
        sb.AppendLine("    {");

        // Nested Result class with DTO
        sb.AppendLine("        public static partial class Result");
        sb.AppendLine("        {");
        EmitDto(sb, projection);
        sb.AppendLine("        }");
        sb.AppendLine();

        // Query methods (use Result.X as the type)
        EmitQueryMethods(sb, query, projection, originalSql, entityName, schema, directives);

        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    public static string EmitCrud(QueryModel query, string originalSql, string entityName, DatabaseSchema? schema = null, Directives.DirectiveModel? directives = null)
    {
        var sb = new System.Text.StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        sb.AppendLine("namespace JauntyQ.Generated");
        sb.AppendLine("{");

        sb.AppendLine($"    public partial class {entityName}");
        sb.AppendLine("    {");

        // Build parameter lists
        var paramListNoConn = new System.Text.StringBuilder();
        var paramListWithConn = new System.Text.StringBuilder();
        paramListWithConn.Append("System.Data.Common.DbConnection conn");

        foreach (var param in query.Parameters)
        {
            string paramType = InferCrudParameterType(param, query, schema, directives);
            if (paramListNoConn.Length > 0)
                paramListNoConn.Append(", ");
            paramListNoConn.Append($"{paramType} {param.Name}");
            paramListWithConn.Append($", {paramType} {param.Name}");
        }

        // Instance method
        EmitCrudMethodBody(sb, query, originalSql, paramListNoConn.ToString(), "_conn", isStatic: false);

        sb.AppendLine();

        // Static method
        EmitCrudMethodBody(sb, query, originalSql, paramListWithConn.ToString(), "conn", isStatic: true);

        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private static void EmitCrudMethodBody(
        System.Text.StringBuilder sb,
        QueryModel query,
        string originalSql,
        string paramList,
        string connVar,
        bool isStatic)
    {
        string modifier = isStatic ? "public static" : "public";
        sb.AppendLine($"        {modifier} int {query.Name}({paramList})");
        sb.AppendLine("        {");

        // Connection lifecycle
        sb.AppendLine($"            bool weOpened = {connVar}.State != System.Data.ConnectionState.Open;");
        sb.AppendLine($"            if (weOpened) {connVar}.Open();");
        sb.AppendLine("            try");
        sb.AppendLine("            {");

        // Create command
        sb.AppendLine($"                using var cmd = {connVar}.CreateCommand();");
        sb.AppendLine($"                cmd.CommandText = @\"{EscapeVerbatimString(originalSql.Trim())}\";");

        // Bind parameters
        for (int i = 0; i < query.Parameters.Count; i++)
        {
            var param = query.Parameters[i];
            string varName = $"p{i}";
            sb.AppendLine();
            sb.AppendLine($"                var {varName} = cmd.CreateParameter();");
            sb.AppendLine($"                {varName}.ParameterName = \"@{param.Name}\";");
            sb.AppendLine($"                {varName}.Value = (object?){param.Name} ?? System.DBNull.Value;");
            sb.AppendLine($"                cmd.Parameters.Add({varName});");
        }

        // Execute
        sb.AppendLine();
        sb.AppendLine("                return cmd.ExecuteNonQuery();");

        // Close try/finally
        sb.AppendLine("            }");
        sb.AppendLine("            finally");
        sb.AppendLine("            {");
        sb.AppendLine($"                if (weOpened) {connVar}.Close();");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
    }

    private static string InferCrudParameterType(ParameterRef param, QueryModel query, DatabaseSchema? schema, Directives.DirectiveModel? directives = null)
    {
        // Check @params directive first
        if (directives?.ExplicitParams != null)
        {
            foreach (var ep in directives.ExplicitParams)
            {
                if (string.Equals(ep.Name, param.Name, StringComparison.OrdinalIgnoreCase))
                    return ep.CSharpType;
            }
        }

        if (!string.IsNullOrEmpty(param.BoundColumnName) && schema != null)
        {
            // For CRUD, the target table is the primary table
            string? targetTable = query.TargetTable;
            if (targetTable != null && schema.Tables.TryGetValue(targetTable, out var tableSchema))
            {
                if (tableSchema.Columns.TryGetValue(param.BoundColumnName, out var colSchema))
                {
                    return DialectMapper.MapDbTypeToCSharp(colSchema.DbType, colSchema.IsNullable);
                }
            }

            // Fallback: try alias-based resolution
            var resolved = ResolveColumnType(param.BoundTableAlias, param.BoundColumnName, query, schema);
            if (resolved != null)
                return resolved;
        }

        return "object";
    }

    public static string EmitEntityCore(string entityName)
    {
        var sb = new System.Text.StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace JauntyQ.Generated");
        sb.AppendLine("{");
        sb.AppendLine($"    public partial class {entityName}");
        sb.AppendLine("    {");
        sb.AppendLine("        private readonly System.Data.Common.DbConnection _conn;");
        sb.AppendLine($"        internal {entityName}(System.Data.Common.DbConnection conn) => _conn = conn;");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    public static string EmitJauntyDb(System.Collections.Generic.IEnumerable<string> entityNames)
    {
        var sb = new System.Text.StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace JauntyQ.Generated");
        sb.AppendLine("{");
        sb.AppendLine("    public class JauntyDb");
        sb.AppendLine("    {");
        sb.AppendLine("        private readonly System.Data.Common.DbConnection _conn;");
        sb.AppendLine();
        sb.AppendLine("        public JauntyDb(System.Data.Common.DbConnection conn) => _conn = conn;");

        foreach (var entity in entityNames)
        {
            string fieldName = "_" + ToCamelCase(entity);
            sb.AppendLine();
            sb.AppendLine($"        private {entity}? {fieldName};");
            sb.AppendLine($"        public {entity} {entity} => {fieldName} ??= new {entity}(_conn);");
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private static void EmitDto(System.Text.StringBuilder sb, ProjectionModel projection)
    {
        sb.AppendLine($"            public class {projection.Name}");
        sb.AppendLine("            {");
        foreach (var col in projection.Columns)
        {
            sb.AppendLine($"                public {col.Type} {col.Name} {{ get; set; }}");
        }
        sb.AppendLine("            }");
    }

    private static void EmitQueryMethods(
        System.Text.StringBuilder sb,
        QueryModel query,
        ProjectionModel projection,
        string originalSql,
        string entityName,
        DatabaseSchema? schema,
        Directives.DirectiveModel? directives = null)
    {
        string returnType = $"Result.{projection.Name}";

        // Build parameter list (without connection)
        var paramListNoConn = new System.Text.StringBuilder();
        var paramListWithConn = new System.Text.StringBuilder();
        paramListWithConn.Append("System.Data.Common.DbConnection conn");

        foreach (var param in query.Parameters)
        {
            string paramType = InferParameterType(param.Name, query, projection, schema, directives);
            if (paramListNoConn.Length > 0)
                paramListNoConn.Append(", ");
            paramListNoConn.Append($"{paramType} {param.Name}");
            paramListWithConn.Append($", {paramType} {param.Name}");
        }

        // Instance method
        EmitMethodBody(sb, query, projection, returnType, originalSql, paramListNoConn.ToString(), "_conn", isStatic: false);

        sb.AppendLine();

        // Static method
        EmitMethodBody(sb, query, projection, returnType, originalSql, paramListWithConn.ToString(), "conn", isStatic: true);
    }

    private static void EmitMethodBody(
        System.Text.StringBuilder sb,
        QueryModel query,
        ProjectionModel projection,
        string returnType,
        string originalSql,
        string paramList,
        string connVar,
        bool isStatic)
    {
        string modifier = isStatic ? "public static" : "public";
        sb.AppendLine($"        {modifier} System.Collections.Generic.List<{returnType}> {query.Name}({paramList})");
        sb.AppendLine("        {");

        // Connection lifecycle
        sb.AppendLine($"            bool weOpened = {connVar}.State != System.Data.ConnectionState.Open;");
        sb.AppendLine($"            if (weOpened) {connVar}.Open();");
        sb.AppendLine("            try");
        sb.AppendLine("            {");

        // Create command
        sb.AppendLine($"                using var cmd = {connVar}.CreateCommand();");
        sb.AppendLine($"                cmd.CommandText = @\"{EscapeVerbatimString(originalSql.Trim())}\";");

        // Bind parameters
        for (int i = 0; i < query.Parameters.Count; i++)
        {
            var param = query.Parameters[i];
            string varName = $"p{i}";
            sb.AppendLine();
            sb.AppendLine($"                var {varName} = cmd.CreateParameter();");
            sb.AppendLine($"                {varName}.ParameterName = \"@{param.Name}\";");
            sb.AppendLine($"                {varName}.Value = (object?){param.Name} ?? System.DBNull.Value;");
            sb.AppendLine($"                cmd.Parameters.Add({varName});");
        }

        // Execute reader
        sb.AppendLine();
        sb.AppendLine("                using var reader = cmd.ExecuteReader();");
        sb.AppendLine($"                var results = new System.Collections.Generic.List<{returnType}>();");
        sb.AppendLine("                while (reader.Read())");
        sb.AppendLine("                {");
        sb.AppendLine($"                    results.Add(new {returnType}");
        sb.AppendLine("                    {");

        // Map columns by ordinal
        for (int i = 0; i < projection.Columns.Count; i++)
        {
            var col = projection.Columns[i];
            string readerCall = GetReaderCall(col.Type, col.Ordinal);
            string comma = i < projection.Columns.Count - 1 ? "," : "";
            sb.AppendLine($"                        {col.Name} = {readerCall}{comma}");
        }

        sb.AppendLine("                    });");
        sb.AppendLine("                }");
        sb.AppendLine("                return results;");

        // Close try/finally
        sb.AppendLine("            }");
        sb.AppendLine("            finally");
        sb.AppendLine("            {");
        sb.AppendLine($"                if (weOpened) {connVar}.Close();");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
    }

    private static string GetReaderCall(string csharpType, int ordinal)
    {
        // Handle nullable types
        bool isNullable = csharpType.EndsWith("?");
        string baseType = isNullable ? csharpType.TrimEnd('?') : csharpType;

        string getMethod = baseType switch
        {
            "int" => $"reader.GetInt32({ordinal})",
            "long" => $"reader.GetInt64({ordinal})",
            "short" => $"reader.GetInt16({ordinal})",
            "bool" => $"reader.GetBoolean({ordinal})",
            "decimal" => $"reader.GetDecimal({ordinal})",
            "double" => $"reader.GetDouble({ordinal})",
            "float" => $"reader.GetFloat({ordinal})",
            "string" => $"reader.GetString({ordinal})",
            "System.DateTime" => $"reader.GetDateTime({ordinal})",
            "System.Guid" => $"reader.GetGuid({ordinal})",
            "byte[]" => $"(byte[])reader.GetValue({ordinal})",
            _ => $"reader.GetValue({ordinal})"
        };

        if (isNullable)
        {
            return $"reader.IsDBNull({ordinal}) ? default : {getMethod}";
        }

        // String is a reference type — always needs null check
        if (csharpType == "string")
        {
            return $"reader.IsDBNull({ordinal}) ? null! : {getMethod}";
        }

        return getMethod;
    }

    public static string InferParameterType(string paramName, QueryModel query, ProjectionModel projection, DatabaseSchema? schema = null, Directives.DirectiveModel? directives = null)
    {
        // 0. Check @params directive first
        if (directives?.ExplicitParams != null)
        {
            foreach (var ep in directives.ExplicitParams)
            {
                if (string.Equals(ep.Name, paramName, StringComparison.OrdinalIgnoreCase))
                    return ep.CSharpType;
            }
        }

        // 1. Try binding-based inference (col = @param parsed by ExtractParameterBindings)
        var paramRef = query.Parameters.FirstOrDefault(p => p.Name == paramName);
        if (paramRef != null && !string.IsNullOrEmpty(paramRef.BoundColumnName) && schema != null)
        {
            var resolved = ResolveColumnType(paramRef.BoundTableAlias, paramRef.BoundColumnName, query, schema);
            if (resolved != null)
                return resolved;
        }

        // 2. Fallback: match parameter name to a projection column name
        foreach (var col in projection.Columns)
        {
            if (col.Name.Equals(DialectMapper.ToPascalCase(paramName), StringComparison.OrdinalIgnoreCase))
            {
                return col.Type;
            }
        }

        return "object";
    }

    private static string? ResolveColumnType(string tableAlias, string columnName, QueryModel query, DatabaseSchema schema)
    {
        if (!string.IsNullOrEmpty(tableAlias))
        {
            // Qualified — resolve alias to table name
            string? tableName = ResolveAlias(tableAlias, query);
            if (tableName != null &&
                schema.Tables.TryGetValue(tableName, out var tableSchema) &&
                tableSchema.Columns.TryGetValue(columnName, out var colSchema))
            {
                return DialectMapper.MapDbTypeToCSharp(colSchema.DbType, colSchema.IsNullable);
            }
        }
        else
        {
            // Unqualified — search all referenced tables
            foreach (var table in query.Tables)
            {
                if (schema.Tables.TryGetValue(table.TableName, out var tableSchema) &&
                    tableSchema.Columns.TryGetValue(columnName, out var colSchema))
                {
                    return DialectMapper.MapDbTypeToCSharp(colSchema.DbType, colSchema.IsNullable);
                }
            }
        }

        return null;
    }

    private static string? ResolveAlias(string alias, QueryModel query)
    {
        foreach (var table in query.Tables)
        {
            string key = !string.IsNullOrEmpty(table.Alias) ? table.Alias : table.TableName;
            if (string.Equals(key, alias, StringComparison.OrdinalIgnoreCase))
                return table.TableName;
        }
        return null;
    }

    private static string ToCamelCase(string name)
    {
        if (string.IsNullOrEmpty(name)) return name;
        return char.ToLowerInvariant(name[0]) + name.Substring(1);
    }

    private static string EscapeVerbatimString(string s)
    {
        return s.Replace("\"", "\"\"");
    }
}
