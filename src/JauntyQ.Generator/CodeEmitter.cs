    private static void EmitQueryMethods(
        System.Text.StringBuilder sb,
        QueryModel query,
        ProjectionModel projection,
        string originalSql,
        string entityName,
        DatabaseSchema? schema,
        Directives.DirectiveModel? directives = null,
        string? procName = null,
        bool isFirst = false,
        string? canonicalRowType = null,
        bool isStream = false)
    {
        string returnType = canonicalRowType ?? $"Result.{projection.Name}";

        var paramInfos = new System.Collections.Generic.List<EmittedParam>();
        foreach (var param in query.Parameters)
        {
            string paramType = InferParameterType(param.Name, query, projection, schema, directives);
            var column = ResolveBoundColumn(param, query, schema, out string? boundTable);
            paramInfos.Add(CreateEmittedParam(param.Name, paramType, isNullable: false, column, boundTable, isWriteTarget: false));
        }

        string queryId = $"{entityName}.{query.Name}";

        // One materializer shared by all four variants. A direct static call
        // (not a delegate): the JIT inlines small static methods, while
        // delegate invocations are indirect calls it will not reliably
        // inline - see docs/design-decisions.md (row materialization).
        // Canonical full-row queries go one step further and share the
        // single Read() materializer on the row POCO itself.
        string mapperCall;
        if (canonicalRowType != null)
        {
            mapperCall = $"{canonicalRowType}.Read(reader)";
        }
        else
        {
            mapperCall = $"__Map{query.Name}(reader)";
            sb.AppendLine($"        private static {returnType} __Map{query.Name}(System.Data.Common.DbDataReader reader) => new {returnType}");
            sb.AppendLine("        {");
            EmitColumnAssignments(sb, projection, indent: "            ");
            sb.AppendLine("        };");
            sb.AppendLine();
        }

        // Instance sync
        EmitMethodBody(sb, query, projection, returnType, originalSql, paramInfos, "_conn", isStatic: false, isAsync: false, isFirst, queryId, mapperCall, procName, schema?.Dialect, isStream);
        sb.AppendLine();
        // Static sync
        EmitMethodBody(sb, query, projection, returnType, originalSql, paramInfos, "conn", isStatic: true, isAsync: false, isFirst, queryId, mapperCall, procName, schema?.Dialect, isStream);
        sb.AppendLine();
        // Instance async
        EmitMethodBody(sb, query, projection, returnType, originalSql, paramInfos, "_conn", isStatic: false, isAsync: true, isFirst, queryId, mapperCall, procName, schema?.Dialect, isStream);
        sb.AppendLine();
        // Static async
        EmitMethodBody(sb, query, projection, returnType, originalSql, paramInfos, "conn", isStatic: true, isAsync: true, isFirst, queryId, mapperCall, procName, schema?.Dialect, isStream);
    }

    private static void EmitMethodBody(
        System.Text.StringBuilder sb,
        QueryModel query,
        ProjectionModel projection,
        string returnType,
        string originalSql,
        System.Collections.Generic.List<EmittedParam> paramInfos,
        string connVar,
        bool isStatic,
        bool isAsync,
        bool isFirst,
        string queryId,
        string mapperCall,
        string? procName = null,
        string? dialect = null,
        bool isStream = false)
    {
        string modifier = isStatic ? "public static" : "public";
        // A streaming method is an iterator: sync -> IEnumerable<T> (no `async`),
        // async -> IAsyncEnumerable<T> with `async`. yield return inside the
        // existing try/finally is legal (no catch), and disposing the enumerator
        // early runs the finally, closing the reader/connection deterministically.
        string asyncModifier = (isAsync && !isStream) ? " async"
            : (isAsync && isStream) ? " async" : "";
        string syncReturn;
        if (isStream)
            syncReturn = isAsync
                ? $"System.Collections.Generic.IAsyncEnumerable<{returnType}>"
                : $"System.Collections.Generic.IEnumerable<{returnType}>";
        else
            syncReturn = isFirst ? $"{returnType}?" : $"System.Collections.Generic.List<{returnType}>";
        // Non-stream async wraps the sync return in Task<>; stream async returns
        // IAsyncEnumerable<T> directly (it is itself awaitable-by-iteration).
        string declaredReturn = (isAsync && !isStream)
            ? $"System.Threading.Tasks.Task<{syncReturn}>"
            : syncReturn;
        string methodName = isAsync ? $"{query.Name}Async" : query.Name;
        // Async streaming iterators need [EnumeratorCancellation] on the token so
        // `await foreach (... .WithCancellation(ct))` flows the token through.
        bool cancelAttr = isAsync && isStream;
        string paramList = BuildParamList(paramInfos, isStatic, isAsync, enumeratorCancellation: cancelAttr);

        sb.AppendLine($"        {modifier}{asyncModifier} {declaredReturn} {methodName}({paramList})");
        sb.AppendLine("        {");

        EmitValueGuards(sb, paramInfos);

        // Connection lifecycle
        sb.AppendLine($"            bool weOpened = {connVar}.State != System.Data.ConnectionState.Open;");
        sb.AppendLine(isAsync
            ? $"            if (weOpened) await {connVar}.OpenAsync(cancellationToken).ConfigureAwait(false);"
            : $"            if (weOpened) {connVar}.Open();");
        sb.AppendLine("            try");
        sb.AppendLine("            {");

        // Create command
        sb.AppendLine($"                using var cmd = {connVar}.CreateCommand();");
        if (!isStatic)
        {
            sb.AppendLine("                if (_db?.CurrentTransaction != null) cmd.Transaction = _db.CurrentTransaction;");
        }
        if (procName != null)
        {
            sb.AppendLine($"                cmd.CommandText = \"{procName}\";");
            sb.AppendLine("                cmd.CommandType = System.Data.CommandType.StoredProcedure;");
        }
        else
        {
            sb.AppendLine($"                cmd.CommandText = @\"{EscapeVerbatimString(StripLeadingSqlComments(originalSql))}\";");
        }

        EmitParameterBinding(sb, paramInfos, dialect);

        // Execute reader + one-time shape guard. SingleResult (and SingleRow
        // for @first) lets the provider optimize buffering for the shape we
        // are guaranteed to consume.
        string behavior = isFirst
            ? "System.Data.CommandBehavior.SingleRow | System.Data.CommandBehavior.SingleResult"
            : "System.Data.CommandBehavior.SingleResult";
        sb.AppendLine();
        sb.AppendLine(isAsync
            ? $"                using var reader = await cmd.ExecuteReaderAsync({behavior}, cancellationToken).ConfigureAwait(false);"
            : $"                using var reader = cmd.ExecuteReader({behavior});");
        sb.AppendLine($"                if (System.Threading.Volatile.Read(ref __{query.Name}Validated) == 0)");
        sb.AppendLine("                {");
        sb.AppendLine($"                    global::JauntyQ.Generated.JauntyQShapeGuard.Validate(reader, __{query.Name}Columns, \"{queryId}\");");
        sb.AppendLine($"                    System.Threading.Volatile.Write(ref __{query.Name}Validated, 1);");
        sb.AppendLine("                }");

        string readCall = isAsync
            ? "await reader.ReadAsync(cancellationToken).ConfigureAwait(false)"
            : "reader.Read()";

        if (isStream)
        {
            // Iterator: yield each row straight off the reader. Nothing is
            // buffered, so memory stays constant regardless of result-set size.
            // The reader/command/connection are held open by the enclosing
            // try/finally until the consumer finishes (or disposes) enumeration.
            sb.AppendLine($"                while ({readCall})");
            sb.AppendLine("                {");
            sb.AppendLine($"                    yield return {mapperCall};");
            sb.AppendLine("                }");
        }
        else if (isFirst)
        {
            sb.AppendLine($"                if (!({readCall}))");
            sb.AppendLine("                    return null;");
            sb.AppendLine($"                return {mapperCall};");
        }
        else
        {
            sb.AppendLine($"                var results = new System.Collections.Generic.List<{returnType}>();");
            sb.AppendLine($"                while ({readCall})");
            sb.AppendLine("                {");
            sb.AppendLine($"                    results.Add({mapperCall});");
            sb.AppendLine("                }");
            sb.AppendLine("                return results;");
        }

        EmitFinallyClose(sb, connVar, isAsync);
        sb.AppendLine("        }");
    }

    private static void EmitColumnAssignments(System.Text.StringBuilder sb, ProjectionModel projection, string indent)
    {
        for (int i = 0; i < projection.Columns.Count; i++)
        {
            var col = projection.Columns[i];
            string readerCall = GetReaderCall(col.Type, col.Ordinal);
            string comma = i < projection.Columns.Count - 1 ? "," : "";
            sb.AppendLine($"{indent}{IdentifierGuard.Escape(col.Name)} = {readerCall}{comma}");
        }
    }

    private static string GetReaderCall(string csharpType, int ordinal)
    {
        // Handle nullable types
        bool isNullable = csharpType.EndsWith("?");
        string baseType = isNullable ? csharpType.TrimEnd('?') : csharpType;

        string getMethod = baseType switch
        {
            "int" => $"reader.GetInt32({ordinal})",
            "long" => $"reader.GetInt64({ordinal})",
            "short" => $"reader.GetInt16({ordinal})",
            "bool" => $"reader.GetBoolean({ordinal})",
            "decimal" => $"reader.GetDecimal({ordinal})",
            "double" => $"reader.GetDouble({ordinal})",
            "float" => $"reader.GetFloat({ordinal})",
            "string" => $"reader.GetString({ordinal})",
            "System.DateTime" => $"reader.GetDateTime({ordinal})",
            "System.Guid" => $"reader.GetGuid({ordinal})",
            "byte[]" => $"(byte[])reader.GetValue({ordinal})",
            _ => $"reader.GetValue({ordinal})"
        };

        if (isNullable)
        {
            return $"reader.IsDBNull({ordinal}) ? default : {getMethod}";
        }

        // String is a reference type — always needs null check
        if (csharpType == "string")
        {
            return $"reader.IsDBNull({ordinal}) ? null! : {getMethod}";
        }

        return getMethod;
    }

    public static string InferParameterType(string paramName, QueryModel query, ProjectionModel projection, DatabaseSchema? schema = null, Directives.DirectiveModel? directives = null)
    {
        // 0. Check @params directive first
        if (directives?.ExplicitParams != null)
        {
            foreach (var ep in directives.ExplicitParams)
            {
                if (string.Equals(ep.Name, paramName, StringComparison.OrdinalIgnoreCase))
                    return ep.CSharpType;
            }
        }

        // 1. Try binding-based inference (col = @param parsed by ExtractParameterBindings)
        var paramRef = query.Parameters.FirstOrDefault(p => p.Name == paramName);
        if (paramRef != null && !string.IsNullOrEmpty(paramRef.BoundColumnName) && schema != null)
        {
            var resolved = ResolveColumnType(paramRef.BoundTableAlias, paramRef.BoundColumnName, query, schema);
            if (resolved != null)
                return resolved;
        }

        // 2. Fallback: match parameter name to a projection column name
        foreach (var col in projection.Columns)
        {
            if (col.Name.Equals(DialectMapper.ToPascalCase(paramName), StringComparison.OrdinalIgnoreCase))
            {
                return col.Type;
            }
        }

        return "object";
    }

    private static string? ResolveColumnType(string tableAlias, string columnName, QueryModel query, DatabaseSchema schema)
    {
        if (!string.IsNullOrEmpty(tableAlias))
        {
            // Qualified — resolve alias to table name
            string? tableName = ResolveAlias(tableAlias, query);
            if (tableName != null &&
                schema.Tables.TryGetValue(tableName, out var tableSchema) &&
                tableSchema.Columns.TryGetValue(columnName, out var colSchema))
            {
                return DialectMapper.MapColumnToCSharp(colSchema);
            }
        }
        else
        {
            // Unqualified — search all referenced tables
            foreach (var table in query.Tables)
            {
                if (schema.Tables.TryGetValue(table.TableName, out var tableSchema) &&
                    tableSchema.Columns.TryGetValue(columnName, out var colSchema))
                {
                    return DialectMapper.MapColumnToCSharp(colSchema);
                }
            }
        }

        return null;
    }

    private static string? ResolveAlias(string alias, QueryModel query)
    {
        foreach (var table in query.Tables)
        {
            string key = !string.IsNullOrEmpty(table.Alias) ? table.Alias : table.TableName;
            if (string.Equals(key, alias, StringComparison.OrdinalIgnoreCase))
                return table.TableName;
        }
        return null;
    }

    private static string ToCamelCase(string name)
    {
        if (string.IsNullOrEmpty(name)) return name;
        return char.ToLowerInvariant(name[0]) + name.Substring(1);
    }

    private static string? ResolveProcName(Directives.DirectiveModel? directives, string entityName, string methodName)
    {
        if (directives == null || !directives.IsProc)
            return null;
        return directives.ProcName ?? $"{entityName}_{methodName}";
    }

    /// <summary>
    /// Strips leading blank lines and leading whole-line `--` comments so
    /// commented-out old queries at the top of a .sql file are not embedded
    /// into every generated CommandText. Mid-query comments are preserved.
    /// </summary>
    internal static string StripLeadingSqlComments(string sql)
    {
        var lines = sql.Split(new[] { "\r\n", "\n" }, StringSplitOptions.None);
        int start = 0;
        while (start < lines.Length)
        {
            var trimmed = lines[start].TrimStart();
            if (trimmed.Length == 0 || trimmed.StartsWith("--"))
            {
                start++;
                continue;
            }
            break;
        }
        return string.Join("\n", lines, start, lines.Length - start).Trim();
    }

    private static void EmitProcScript(
        System.Text.StringBuilder sb,
        string procName,
        string methodName,
        string originalSql,
        QueryModel query,
        ProjectionModel? projection,
        DatabaseSchema? schema,
        Directives.DirectiveModel? directives,
        bool isCrud)
    {
        // Build parameter list for CREATE PROCEDURE
        var procParams = new System.Collections.Generic.List<string>();
        foreach (var param in query.Parameters)
        {
            string csharpType;
            if (isCrud)
                csharpType = InferCrudParameterType(param, query, schema, directives);
            else if (projection != null)
                csharpType = InferParameterType(param.Name, query, projection, schema, directives);
            else
                csharpType = "object";

            var sqlType = CSharpToSqlTypeMapper.Map(csharpType);
            procParams.Add($"    @{param.Name} {sqlType}");
        }

        var paramBlock = procParams.Count > 0
            ? "\n" + string.Join(",\n", procParams) + "\n"
            : "";

        var procSql = $"CREATE OR ALTER PROCEDURE [{procName}]{paramBlock}AS\nBEGIN\n    SET NOCOUNT ON;\n    {StripLeadingSqlComments(originalSql)}\nEND";

        sb.AppendLine("        public static partial class Proc");
        sb.AppendLine("        {");
        sb.AppendLine($"            public const string {methodName} = @\"{EscapeVerbatimString(procSql)}\";");
        sb.AppendLine("        }");
    }

    /// <summary>
    /// Emits a typed call to a stored procedure that already exists in the
    /// database (bound via -- @call). Unlike EmitProcScript, JauntyQ does not
    /// author the body — it reads the callable contract (params, result columns)
    /// from the schema snapshot and emits a CommandType.StoredProcedure call
    /// with ordinal result materialization. Supports IN and OUT/INOUT params;
    /// v1 handles a single result set.
    /// </summary>
    public static string EmitProcCall(string entityName, string methodName, JauntyQ.Schema.ProcedureSchema procedure, string? dialect)
    {
        var sb = new System.Text.StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace JauntyQ.Generated");
        sb.AppendLine("{");
        sb.AppendLine($"    public partial class {entityName}");
        sb.AppendLine("    {");

        bool hasResults = procedure.Results.Count > 0;
        string resultType = $"Result.{methodName}";

        // Result DTO (only when the proc returns rows).
        if (hasResults)
        {
            sb.AppendLine("        public static partial class Result");
            sb.AppendLine("        {");
            sb.AppendLine($"            public class {methodName}");
            sb.AppendLine("            {");
            foreach (var col in procedure.Results)
            {
                string ct = DialectMapper.MapColumnToCSharp(col);
                sb.AppendLine($"                public required {ct} {IdentifierGuard.Escape(DialectMapper.ToPascalCase(col.Name))} {{ get; set; }}");
            }
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine();

            // Ordinal materializer (mirrors the SELECT path).
            sb.AppendLine($"        private static {resultType} __Map{methodName}(System.Data.Common.DbDataReader reader) => new {resultType}");
            sb.AppendLine("        {");
            for (int i = 0; i < procedure.Results.Count; i++)
            {
                var col = procedure.Results[i];
                string ct = DialectMapper.MapColumnToCSharp(col);
                string comma = i < procedure.Results.Count - 1 ? "," : "";
                sb.AppendLine($"            {IdentifierGuard.Escape(DialectMapper.ToPascalCase(col.Name))} = {GetReaderCall(ct, i)}{comma}");
            }
            sb.AppendLine("        };");
            sb.AppendLine();
        }

        EmitProcCallBody(sb, methodName, procedure, resultType, hasResults, "_conn", isStatic: false, isAsync: false, dialect);
        sb.AppendLine();
        EmitProcCallBody(sb, methodName, procedure, resultType, hasResults, "conn", isStatic: true, isAsync: false, dialect);
        sb.AppendLine();
        EmitProcCallBody(sb, methodName, procedure, resultType, hasResults, "_conn", isStatic: false, isAsync: true, dialect);
        sb.AppendLine();
        EmitProcCallBody(sb, methodName, procedure, resultType, hasResults, "conn", isStatic: true, isAsync: true, dialect);

        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void EmitProcCallBody(
        System.Text.StringBuilder sb,
        string methodName,
        JauntyQ.Schema.ProcedureSchema procedure,
        string resultType,
        bool hasResults,
        string connVar,
        bool isStatic,
        bool isAsync,
        string? dialect)
    {
        string modifier = isStatic ? "public static" : "public";
        string asyncModifier = isAsync ? " async" : "";
        // Return: List<Result> for row-returning procs, else int (row count).
        string syncReturn = hasResults ? $"System.Collections.Generic.List<{resultType}>" : "int";
        string declaredReturn = isAsync ? $"System.Threading.Tasks.Task<{syncReturn}>" : syncReturn;
        string name = isAsync ? $"{methodName}Async" : methodName;

        // Parameter list: IN params by value, OUT/INOUT params as C# `out`.
        var parts = new System.Collections.Generic.List<string>();
        if (isStatic)
            parts.Add("System.Data.Common.DbConnection conn");
        foreach (var p in procedure.Params)
        {
            if (p.Direction == JauntyQ.Schema.ProcedureParamDirection.ReturnValue)
                continue;
            string ct = DialectMapper.MapDbTypeToCSharp(p.DbType, p.IsNullable);
            string pname = IdentifierGuard.Escape(ToCamelCase(DialectMapper.ToPascalCase(p.Name)));
            if (p.Direction == JauntyQ.Schema.ProcedureParamDirection.Out)
                parts.Add($"out {ct} {pname}");
            else if (p.Direction == JauntyQ.Schema.ProcedureParamDirection.InOut)
                parts.Add($"ref {ct} {pname}");
            else
                parts.Add($"{ct} {pname}");
        }
        if (isAsync)
            parts.Add("System.Threading.CancellationToken cancellationToken = default");

        sb.AppendLine($"        {modifier}{asyncModifier} {declaredReturn} {name}({string.Join(", ", parts)})");
        sb.AppendLine("        {");

        // Pre-assign out params so the method is definitely-assigned on all paths.
        foreach (var p in procedure.Params)
        {
            if (p.Direction == JauntyQ.Schema.ProcedureParamDirection.Out)
            {
                string pname = IdentifierGuard.Escape(ToCamelCase(DialectMapper.ToPascalCase(p.Name)));
                sb.AppendLine($"            {pname} = default;");
            }
        }

        sb.AppendLine($"            bool weOpened = {connVar}.State != System.Data.ConnectionState.Open;");
        sb.AppendLine(isAsync
            ? $"            if (weOpened) await {connVar}.OpenAsync(cancellationToken).ConfigureAwait(false);"
            : $"            if (weOpened) {connVar}.Open();");
        sb.AppendLine("            try");
        sb.AppendLine("            {");
        sb.AppendLine($"                using var cmd = {connVar}.CreateCommand();");
        if (!isStatic)
            sb.AppendLine("                if (_db?.CurrentTransaction != null) cmd.Transaction = _db.CurrentTransaction;");
        sb.AppendLine($"                cmd.CommandText = \"{IdentifierGuard.ToStringLiteral(procedure.Name)}\";");
        sb.AppendLine("                cmd.CommandType = System.Data.CommandType.StoredProcedure;");

        // Bind parameters. Track OUT/INOUT parameter variable names for readback.
        var outReadback = new System.Collections.Generic.List<(string ParamVar, string CSharpName, string CSharpType, bool Nullable)>();
        int idx = 0;
        foreach (var p in procedure.Params)
        {
            if (p.Direction == JauntyQ.Schema.ProcedureParamDirection.ReturnValue)
                continue;
            string varName = $"p{idx++}";
            string ct = DialectMapper.MapDbTypeToCSharp(p.DbType, p.IsNullable);
            string pname = IdentifierGuard.Escape(ToCamelCase(DialectMapper.ToPascalCase(p.Name)));
            sb.AppendLine($"                var {varName} = cmd.CreateParameter();");
            sb.AppendLine($"                {varName}.ParameterName = \"@{p.Name}\";");
            string? adoDbType = MapCSharpTypeToAdoDbType(ct);
            if (adoDbType != null)
                sb.AppendLine($"                {varName}.DbType = System.Data.DbType.{adoDbType};");
            switch (p.Direction)
            {
                case JauntyQ.Schema.ProcedureParamDirection.Out:
                    sb.AppendLine($"                {varName}.Direction = System.Data.ParameterDirection.Output;");
                    if (p.MaxLength is int ml && ml != 0)
                        sb.AppendLine($"                {varName}.Size = {ml};");
                    outReadback.Add((varName, pname, ct, p.IsNullable || !IsNonNullableValueType(ct)));
                    break;
                case JauntyQ.Schema.ProcedureParamDirection.InOut:
                    sb.AppendLine($"                {varName}.Direction = System.Data.ParameterDirection.InputOutput;");
                    if (p.MaxLength is int ml2 && ml2 != 0)
                        sb.AppendLine($"                {varName}.Size = {ml2};");
                    sb.AppendLine(IsNonNullableValueType(ct)
                        ? $"                {varName}.Value = {pname};"
                        : $"                {varName}.Value = (object?){pname} ?? System.DBNull.Value;");
                    outReadback.Add((varName, pname, ct, p.IsNullable || !IsNonNullableValueType(ct)));
                    break;
                default:
                    sb.AppendLine(IsNonNullableValueType(ct)
                        ? $"                {varName}.Value = {pname};"
                        : $"                {varName}.Value = (object?){pname} ?? System.DBNull.Value;");
                    break;
            }
            sb.AppendLine($"                cmd.Parameters.Add({varName});");
        }
        sb.AppendLine();

        if (hasResults)
        {
            string behavior = "System.Data.CommandBehavior.SingleResult";
            sb.AppendLine(isAsync
                ? $"                using (var reader = await cmd.ExecuteReaderAsync({behavior}, cancellationToken).ConfigureAwait(false))"
                : $"                using (var reader = cmd.ExecuteReader({behavior}))");
            sb.AppendLine("                {");
            sb.AppendLine($"                    var results = new System.Collections.Generic.List<{resultType}>();");
            string readCall = isAsync ? "await reader.ReadAsync(cancellationToken).ConfigureAwait(false)" : "reader.Read()";
            sb.AppendLine($"                    while ({readCall})");
            sb.AppendLine($"                        results.Add(__Map{methodName}(reader));");
            EmitProcOutReadback(sb, outReadback, "                    ");
            sb.AppendLine("                    return results;");
            sb.AppendLine("                }");
        }
        else
        {
            sb.AppendLine(isAsync
                ? "                int __affected = await cmd.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);"
                : "                int __affected = cmd.ExecuteNonQuery();");
            EmitProcOutReadback(sb, outReadback, "                ");
            sb.AppendLine("                return __affected;");
        }

        EmitFinallyClose(sb, connVar, isAsync);
        sb.AppendLine("        }");
    }

    /// <summary>Reads OUT/INOUT parameter values back into the C# out/ref args.</summary>
    private static void EmitProcOutReadback(
        System.Text.StringBuilder sb,
        System.Collections.Generic.List<(string ParamVar, string CSharpName, string CSharpType, bool Nullable)> outParams,
        string indent)
    {
        foreach (var (paramVar, csName, csType, nullable) in outParams)
        {
            string baseType = csType.EndsWith("?") ? csType.Substring(0, csType.Length - 1) : csType;
            // DBNull -> default; otherwise unbox to the declared type.
            sb.AppendLine($"{indent}{csName} = {paramVar}.Value is null || {paramVar}.Value is System.DBNull ? default! : ({csType})({baseType}){paramVar}.Value;");
        }
    }

    private static string EscapeVerbatimString(string s)
    {
        return s.Replace("\"", "\"\"");
    }
