using JauntyQ.Schema;
using JauntyQ.SqlParser.IR;

namespace JauntyQ.Generator;

public static class CodeEmitter
{
    public static string Emit(QueryModel query, ProjectionModel projection, string originalSql, string entityName, DatabaseSchema? schema = null, Directives.DirectiveModel? directives = null, string? canonicalRowType = null)
    {
        var sb = new System.Text.StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        sb.AppendLine("namespace JauntyQ.Generated");
        sb.AppendLine("{");

        // Entity partial class containing nested Result class and query methods
        sb.AppendLine($"    public partial class {entityName}");
        sb.AppendLine("    {");

        // Full-row projections return the canonical per-table POCO (e.g.
        // Shipper) instead of a query-specific nested Result type; only
        // genuine custom projections (joins, partial selects) get their own.
        if (canonicalRowType == null)
        {
            sb.AppendLine("        public static partial class Result");
            sb.AppendLine("        {");
            EmitDto(sb, projection);
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        // Expected result-set column names for the one-time shape guard
        EmitColumnNames(sb, query.Name, projection);
        sb.AppendLine();

        // Resolve proc name (null if not in proc mode)
        string? procName = ResolveProcName(directives, entityName, query.Name);

        bool isFirst = directives?.IsFirst == true;
        bool isStream = directives?.IsStream == true;

        // Query methods (use Result.X as the type)
        EmitQueryMethods(sb, query, projection, originalSql, entityName, schema, directives, procName, isFirst, canonicalRowType, isStream);

        // Emit Proc nested class with CREATE PROCEDURE script
        if (procName != null)
        {
            sb.AppendLine();
            EmitProcScript(sb, procName, query.Name, originalSql, query, projection, schema, directives, isCrud: false);
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    public static string EmitCrud(QueryModel query, string originalSql, string entityName, DatabaseSchema? schema = null, Directives.DirectiveModel? directives = null)
    {
        var sb = new System.Text.StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        sb.AppendLine("namespace JauntyQ.Generated");
        sb.AppendLine("{");

        sb.AppendLine($"    public partial class {entityName}");
        sb.AppendLine("    {");

        // Build parameter lists
        var paramInfos = new System.Collections.Generic.List<EmittedParam>();
        foreach (var param in query.Parameters)
        {
            string paramType = InferCrudParameterType(param, query, schema, directives);
            bool isNullable = IsBoundColumnNullable(param, query, schema);
            var column = ResolveBoundColumn(param, query, schema, out string? boundTable);
            paramInfos.Add(CreateEmittedParam(param.Name, paramType, isNullable, column, boundTable, param.IsWriteTarget));
        }

        // Resolve proc name (null if not in proc mode)
        string? procName = ResolveProcName(directives, entityName, query.Name);

        // -- @identity: resolve the single identity key column of the target
        // table (the generator validates preconditions and reports JNT7001;
        // by the time we emit, this either resolves or the file was skipped).
        IdentityInfo? identity = ResolveIdentityInfo(query, schema, directives);

        // Instance sync
        EmitCrudMethodBody(sb, query, originalSql, paramInfos, "_conn", isStatic: false, isAsync: false, procName: procName, identity: identity, dialect: schema?.Dialect);
        sb.AppendLine();
        // Static sync
        EmitCrudMethodBody(sb, query, originalSql, paramInfos, "conn", isStatic: true, isAsync: false, procName: procName, identity: identity, dialect: schema?.Dialect);
        sb.AppendLine();
        // Instance async
        EmitCrudMethodBody(sb, query, originalSql, paramInfos, "_conn", isStatic: false, isAsync: true, procName: procName, identity: identity, dialect: schema?.Dialect);
        sb.AppendLine();
        // Static async
        EmitCrudMethodBody(sb, query, originalSql, paramInfos, "conn", isStatic: true, isAsync: true, procName: procName, identity: identity, dialect: schema?.Dialect);

        // Emit Proc nested class with CREATE PROCEDURE script
        if (procName != null)
        {
            sb.AppendLine();
            EmitProcScript(sb, procName, query.Name, originalSql, query, null, schema, directives, isCrud: true);
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// Source for the shared one-time result-set shape guard. Registered by the
    /// generator as post-initialization output so it exists exactly once.
    /// </summary>
    public static string EmitShapeGuardSource()
    {
        return """
// <auto-generated/>
#nullable enable

namespace JauntyQ.Generated
{
    /// <summary>
    /// Validates the result-set shape against the schema snapshot. The caller
    /// latches this so it runs on the first execution of each query per process
    /// and never again (never per row, never per subsequent call). Catches drift
    /// between the live database and the snapshot instead of silently mapping
    /// wrong ordinals.
    /// </summary>
    public static class JauntyQShapeGuard
    {
        public static void Validate(System.Data.Common.DbDataReader reader, string[] expectedColumns, string queryId)
        {
            if (reader.FieldCount < expectedColumns.Length)
            {
                throw new System.InvalidOperationException(
                    $"JauntyQ schema drift in {queryId}: expected {expectedColumns.Length} columns but the result set has {reader.FieldCount}. " +
                    "The database no longer matches the schema snapshot; re-run 'jaunty schema pull' and rebuild.");
            }

            for (int i = 0; i < expectedColumns.Length; i++)
            {
                string actual = reader.GetName(i);
                if (!string.Equals(actual, expectedColumns[i], System.StringComparison.OrdinalIgnoreCase))
                {
                    throw new System.InvalidOperationException(
                        $"JauntyQ schema drift in {queryId}: expected column '{expectedColumns[i]}' at ordinal {i} but the result set returned '{actual}'. " +
                        "The database no longer matches the schema snapshot; re-run 'jaunty schema pull' and rebuild.");
                }
            }
        }
    }
}
""";
    }

    private readonly struct EmittedParam
    {
        public readonly string Name;
        public readonly string CSharpType;
        public readonly bool IsNullable;
        public readonly int? MaxLength;       // chars for text, bytes for binary; -1 = unbounded (MAX)
        public readonly int? Precision;
        public readonly int? Scale;
        public readonly bool IsWriteTarget;   // INSERT value / UPDATE SET / upsert column
        public readonly string? ColumnDisplay; // "table.column" for guard messages

        public EmittedParam(string name, string csharpType, bool isNullable = false,
            int? maxLength = null, int? precision = null, int? scale = null,
            bool isWriteTarget = false, string? columnDisplay = null)
        {
            Name = name;
            CSharpType = csharpType;
            IsNullable = isNullable;
            MaxLength = maxLength;
            Precision = precision;
            Scale = scale;
            IsWriteTarget = isWriteTarget;
            ColumnDisplay = columnDisplay;
        }
    }

    /// <summary>
    /// Resolves the schema column a parameter is bound to (CRUD target table
    /// first, then alias-qualified, then unique unqualified match).
    /// </summary>
    private static ColumnSchema? ResolveBoundColumn(ParameterRef param, QueryModel query, DatabaseSchema? schema, out string? tableName)
    {
        tableName = null;
        if (schema == null || string.IsNullOrEmpty(param.BoundColumnName))
            return null;

        if (query.TargetTable != null &&
            schema.Tables.TryGetValue(query.TargetTable, out var target) &&
            target.Columns.TryGetValue(param.BoundColumnName, out var targetCol))
        {
            tableName = query.TargetTable;
            return targetCol;
        }

        if (!string.IsNullOrEmpty(param.BoundTableAlias))
        {
            string? resolved = ResolveAlias(param.BoundTableAlias, query);
            if (resolved != null &&
                schema.Tables.TryGetValue(resolved, out var aliased) &&
                aliased.Columns.TryGetValue(param.BoundColumnName, out var aliasedCol))
            {
                tableName = resolved;
                return aliasedCol;
            }
            return null;
        }

        foreach (var table in query.Tables)
        {
            if (schema.Tables.TryGetValue(table.TableName, out var tableSchema) &&
                tableSchema.Columns.TryGetValue(param.BoundColumnName, out var col))
            {
                tableName = table.TableName;
                return col;
            }
        }
        return null;
    }

    private static EmittedParam CreateEmittedParam(string name, string csharpType, bool isNullable,
        ColumnSchema? column, string? tableName, bool isWriteTarget)
    {
        if (column == null)
            return new EmittedParam(name, csharpType, isNullable);
        return new EmittedParam(name, csharpType, isNullable,
            column.MaxLength, column.Precision, column.Scale, isWriteTarget,
            tableName != null ? $"{tableName}.{column.Name}" : column.Name);
    }

    /// <summary>
    /// Client-side length guards for write parameters. Fails fast with the
    /// exact column and limit instead of a server round-trip ending in a
    /// truncation error; also what makes the fixed DbParameter.Size safe
    /// (ADO.NET providers silently truncate oversize values to Size).
    /// </summary>
    private static void EmitValueGuards(System.Text.StringBuilder sb, System.Collections.Generic.List<EmittedParam> paramInfos)
    {
        bool any = false;
        foreach (var param in paramInfos)
        {
            if (!param.IsWriteTarget || param.MaxLength is not int max || max <= 0)
                continue;
            bool isText = param.CSharpType is "string" or "string?";
            bool isBinary = param.CSharpType is "byte[]" or "byte[]?";
            if (!isText && !isBinary)
                continue;
            string unit = isText ? "characters" : "bytes";
            string condition = param.CSharpType is "string" or "byte[]"
                ? $"{param.Name}.Length > {max}"
                : $"{param.Name} != null && {param.Name}.Length > {max}";
            sb.AppendLine($"            if ({condition})");
            sb.AppendLine($"                throw new System.ArgumentException($\"Value ({{{param.Name}.Length}} {unit}) exceeds {param.ColumnDisplay} max length ({max}).\", nameof({param.Name}));");
            any = true;
        }
        if (any)
            sb.AppendLine();
    }

    /// <summary>
    /// DbParameter.Size / Precision / Scale from the schema snapshot.
    /// Fixed Size keeps the server plan cache to one plan per query instead
    /// of one per distinct value length. Write parameters are guarded above,
    /// so the fixed Size can never truncate; comparison parameters size
    /// dynamically because a truncated key could match the wrong row.
    /// </summary>
    private static void EmitParameterSizing(System.Text.StringBuilder sb, EmittedParam param, string varName)
    {
        bool isText = param.CSharpType is "string" or "string?";
        bool isBinary = param.CSharpType is "byte[]" or "byte[]?";
        if ((isText || isBinary) && param.MaxLength is int max)
        {
            if (max < 0)
            {
                sb.AppendLine($"                {varName}.Size = -1;");
            }
            else if (param.IsWriteTarget)
            {
                sb.AppendLine($"                {varName}.Size = {max};");
            }
            else
            {
                string sizeExpr = param.CSharpType is "string" or "byte[]"
                    ? $"{param.Name}.Length > {max} ? {param.Name}.Length : {max}"
                    : $"{param.Name} == null ? {max} : ({param.Name}.Length > {max} ? {param.Name}.Length : {max})";
                sb.AppendLine($"                {varName}.Size = {sizeExpr};");
            }
        }

        if (param.CSharpType is "decimal" or "decimal?" && param.Precision is int precision && precision > 0)
        {
            sb.AppendLine($"                {varName}.Precision = {precision};");
            sb.AppendLine($"                {varName}.Scale = {param.Scale ?? 0};");
        }
    }

    private static void EmitColumnNames(System.Text.StringBuilder sb, string methodName, ProjectionModel projection)
    {
        sb.Append($"        private static readonly string[] __{methodName}Columns = {{ ");
        for (int i = 0; i < projection.Columns.Count; i++)
        {
            var col = projection.Columns[i];
            string sourceName = string.IsNullOrEmpty(col.SourceName) ? col.Name : col.SourceName;
            if (i > 0) sb.Append(", ");
            // JNT2004 (C3): sourceName comes from a SQL alias/column and is
            // embedded in a regular string literal; encode it so a quote or
            // backslash cannot break out of the literal.
            sb.Append($"\"{IdentifierGuard.ToStringLiteral(sourceName)}\"");
        }
        sb.AppendLine(" };");
        // One-time shape-guard latch (0 = not yet validated). The guard runs on
        // the first execution of this query per process and never again, so the
        // per-row-free drift check is also per-query-once, as documented.
        sb.AppendLine($"        private static int __{methodName}Validated;");
    }

    private static void EmitCrudMethodBody(
        System.Text.StringBuilder sb,
        QueryModel query,
        string originalSql,
        System.Collections.Generic.List<EmittedParam> paramInfos,
        string connVar,
        bool isStatic,
        bool isAsync,
        string? procName = null,
        IdentityInfo? identity = null,
        string? dialect = null)
    {
        string modifier = isStatic ? "public static" : "public";
        string asyncModifier = isAsync ? " async" : "";
        string syncReturn = identity != null ? identity.Value.CSharpType : "int";
        string returnType = isAsync ? $"System.Threading.Tasks.Task<{syncReturn}>" : syncReturn;
        string methodName = isAsync ? $"{query.Name}Async" : query.Name;
        string paramList = BuildParamList(paramInfos, isStatic, isAsync, trailingNullableDefaults: true);

        sb.AppendLine($"        {modifier}{asyncModifier} {returnType} {methodName}({paramList})");
        sb.AppendLine("        {");

        EmitValueGuards(sb, paramInfos);

        // Connection lifecycle
        sb.AppendLine($"            bool weOpened = {connVar}.State != System.Data.ConnectionState.Open;");
        sb.AppendLine(isAsync
            ? $"            if (weOpened) await {connVar}.OpenAsync(cancellationToken).ConfigureAwait(false);"
            : $"            if (weOpened) {connVar}.Open();");
        sb.AppendLine("            try");
        sb.AppendLine("            {");

        // Create command
        sb.AppendLine($"                using var cmd = {connVar}.CreateCommand();");
        if (!isStatic)
        {
            sb.AppendLine("                if (_db?.CurrentTransaction != null) cmd.Transaction = _db.CurrentTransaction;");
        }
        if (procName != null)
        {
            sb.AppendLine($"                cmd.CommandText = \"{procName}\";");
            sb.AppendLine("                cmd.CommandType = System.Data.CommandType.StoredProcedure;");
        }
        else if (identity != null)
        {
            string identitySql = BuildIdentityInsertSql(
                StripLeadingSqlComments(originalSql), identity.Value.Dialect, identity.Value.ColumnName);
            sb.AppendLine($"                cmd.CommandText = @\"{EscapeVerbatimString(identitySql)}\";");
        }
        else
        {
            sb.AppendLine($"                cmd.CommandText = @\"{EscapeVerbatimString(StripLeadingSqlComments(originalSql))}\";");
        }

        EmitParameterBinding(sb, paramInfos, dialect);

        // Execute
        sb.AppendLine();
        if (identity != null)
        {
            string behavior = "System.Data.CommandBehavior.SingleRow | System.Data.CommandBehavior.SingleResult";
            sb.AppendLine(isAsync
                ? $"                using var reader = await cmd.ExecuteReaderAsync({behavior}, cancellationToken).ConfigureAwait(false);"
                : $"                using var reader = cmd.ExecuteReader({behavior});");
            string readCall = isAsync
                ? "await reader.ReadAsync(cancellationToken).ConfigureAwait(false)"
                : "reader.Read()";
            sb.AppendLine($"                if (!({readCall}))");
            sb.AppendLine("                    throw new System.InvalidOperationException(\"INSERT did not return an identity value.\");");
            sb.AppendLine($"                return {GetIdentityReaderCall(identity.Value)};");
        }
        else
        {
            sb.AppendLine(isAsync
                ? "                return await cmd.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);"
                : "                return cmd.ExecuteNonQuery();");
        }

        EmitFinallyClose(sb, connVar, isAsync);
        sb.AppendLine("        }");
    }

    private static string BuildParamList(System.Collections.Generic.List<EmittedParam> paramInfos, bool isStatic, bool isAsync, bool trailingNullableDefaults = false, bool enumeratorCancellation = false)
    {
        // C# optional parameters must be trailing: give `= default` to the
        // longest suffix of nullable-column parameters so callers pass only
        // what the schema actually requires.
        int firstDefault = paramInfos.Count;
        if (trailingNullableDefaults)
        {
            while (firstDefault > 0 && paramInfos[firstDefault - 1].IsNullable)
                firstDefault--;
        }

        var sb = new System.Text.StringBuilder();
        if (isStatic)
            sb.Append("System.Data.Common.DbConnection conn");

        for (int i = 0; i < paramInfos.Count; i++)
        {
            var p = paramInfos[i];
            if (sb.Length > 0) sb.Append(", ");
            sb.Append($"{p.CSharpType} {p.Name}");
            if (i >= firstDefault) sb.Append(" = default");
        }

        if (isAsync)
        {
            if (sb.Length > 0) sb.Append(", ");
            // Async streaming iterators annotate the token so the framework can
            // flow a token supplied via await foreach (...).WithCancellation(ct).
            if (enumeratorCancellation)
                sb.Append("[System.Runtime.CompilerServices.EnumeratorCancellation] ");
            sb.Append("System.Threading.CancellationToken cancellationToken = default");
        }

        return sb.ToString();
    }

    private static void EmitParameterBinding(System.Text.StringBuilder sb, System.Collections.Generic.List<EmittedParam> paramInfos, string? dialect = null)
    {
        for (int i = 0; i < paramInfos.Count; i++)
        {
            var param = paramInfos[i];
            string varName = $"p{i}";
            sb.AppendLine();

            // PostgreSQL: NpgsqlParameter<T>.TypedValue keeps the value
            // strongly typed end to end - no object boxing at the ADO.NET
            // boundary, and Npgsql infers the exact wire type from T (no
            // DbType). PostgreSQL parameter typing is OID-based, so the
            // per-length plan-cache concern does not apply and Size is not
            // emitted; the client-side write guards still run.
            if (string.Equals(dialect, "postgres", StringComparison.OrdinalIgnoreCase))
            {
                sb.AppendLine($"                var {varName} = new global::Npgsql.NpgsqlParameter<{param.CSharpType}> {{ ParameterName = \"@{param.Name}\", TypedValue = {param.Name} }};");
                sb.AppendLine($"                cmd.Parameters.Add({varName});");
                continue;
            }

            sb.AppendLine($"                var {varName} = cmd.CreateParameter();");
            sb.AppendLine($"                {varName}.ParameterName = \"@{param.Name}\";");
            string? adoDbType = MapCSharpTypeToAdoDbType(param.CSharpType);
            if (adoDbType != null)
            {
                sb.AppendLine($"                {varName}.DbType = System.Data.DbType.{adoDbType};");
            }
            EmitParameterSizing(sb, param, varName);
            // DbParameter.Value is object, so value types box exactly once per
            // call here - an ADO.NET boundary cost every library pays. For
            // non-nullable value types the DBNull coalesce is dead code, so
            // emit a plain assignment; the (object?) dance is only needed
            // where null is actually possible.
            if (IsNonNullableValueType(param.CSharpType))
            {
                sb.AppendLine($"                {varName}.Value = {param.Name};");
            }
            else
            {
                sb.AppendLine($"                {varName}.Value = (object?){param.Name} ?? System.DBNull.Value;");
            }
            sb.AppendLine($"                cmd.Parameters.Add({varName});");
        }
    }

    internal readonly struct IdentityInfo
    {
        public readonly string ColumnName;
        public readonly string CSharpType;
        public readonly string Dialect;

        public IdentityInfo(string columnName, string csharpType, string dialect)
        {
            ColumnName = columnName;
            CSharpType = csharpType;
            Dialect = dialect;
        }
    }

    /// <summary>
    /// Resolves the single identity key column for an -- @identity INSERT.
    /// Returns null when preconditions are not met (the generator reports
    /// JNT7001 for user files before emission; synthetics only carry the
    /// directive when resolvable).
    /// </summary>
    internal static IdentityInfo? ResolveIdentityInfo(QueryModel query, DatabaseSchema? schema, Directives.DirectiveModel? directives)
    {
        if (directives?.ReturnsIdentity != true || schema == null || string.IsNullOrEmpty(schema.Dialect))
            return null;
        if (query.StatementType != StatementType.Insert || query.TargetTable == null)
            return null;
        if (!schema.Tables.TryGetValue(query.TargetTable, out var tableSchema))
            return null;

        ColumnSchema? identityCol = null;
        foreach (var col in tableSchema.Columns.Values)
        {
            if (!col.IsIdentity)
                continue;
            if (identityCol != null)
                return null; // multiple identity columns: unsupported
            identityCol = col;
        }
        if (identityCol == null)
            return null;

        string csharpType = DialectMapper.MapDbTypeToCSharp(identityCol.DbType, isNullable: false);
        return new IdentityInfo(identityCol.Name, csharpType, schema.Dialect);
    }

    /// <summary>
    /// Rewrites a plain INSERT so it returns the database-assigned identity:
    /// OUTPUT INSERTED.x (SQL Server, before VALUES), RETURNING x
    /// (PostgreSQL/SQLite), or a trailing SELECT LAST_INSERT_ID() (MySQL).
    /// </summary>
    internal static string BuildIdentityInsertSql(string sql, string dialect, string identityColumn)
    {
        string trimmed = sql.TrimEnd();
        while (trimmed.EndsWith(";"))
            trimmed = trimmed.Substring(0, trimmed.Length - 1).TrimEnd();

        switch (dialect)
        {
            case "sqlserver":
            {
                int idx = FindValuesKeyword(trimmed);
                if (idx < 0)
                    return trimmed; // generator validated the shape; defensive only
                return trimmed.Substring(0, idx) + $"output inserted.{identityColumn}\n" + trimmed.Substring(idx);
            }
            case "postgres":
            case "sqlite":
                return trimmed + $"\nreturning {identityColumn}";
            case "mysql":
                return trimmed + ";\nselect last_insert_id()";
            default:
                return trimmed;
        }
    }

    private static int FindValuesKeyword(string sql)
    {
        for (int i = 0; i + 6 <= sql.Length; i++)
        {
            if (string.Compare(sql, i, "values", 0, 6, StringComparison.OrdinalIgnoreCase) != 0)
                continue;
            bool startOk = i == 0 || !char.IsLetterOrDigit(sql[i - 1]) && sql[i - 1] != '_' && sql[i - 1] != '@';
            bool endOk = i + 6 == sql.Length || !char.IsLetterOrDigit(sql[i + 6]) && sql[i + 6] != '_';
            if (startOk && endOk)
                return i;
        }
        return -1;
    }

    private static string GetIdentityReaderCall(IdentityInfo identity)
    {
        // MySQL's LAST_INSERT_ID() is BIGINT UNSIGNED regardless of the key
        // type; read as long and narrow explicitly.
        if (identity.Dialect == "mysql" && identity.CSharpType != "long")
            return $"checked(({identity.CSharpType})reader.GetInt64(0))";
        return GetReaderCall(identity.CSharpType, 0);
    }

    private static void EmitFinallyClose(System.Text.StringBuilder sb, string connVar, bool isAsync)
    {
        sb.AppendLine("            }");
        sb.AppendLine("            finally");
        sb.AppendLine("            {");
        sb.AppendLine(isAsync
            ? $"                if (weOpened) await {connVar}.CloseAsync().ConfigureAwait(false);"
            : $"                if (weOpened) {connVar}.Close();");
        sb.AppendLine("            }");
    }

    private static bool IsNonNullableValueType(string csharpType) => csharpType switch
    {
        "int" or "long" or "short" or "bool" or "decimal" or "double" or "float"
            or "System.DateTime" or "System.TimeSpan" or "System.Guid" => true,
        _ => false
    };

    /// <summary>
    /// Maps an emitted C# parameter type to System.Data.DbType so providers skip
    /// runtime type inference. Returns null when no static mapping exists.
    /// </summary>
    private static string? MapCSharpTypeToAdoDbType(string csharpType)
    {
        string baseType = csharpType.EndsWith("?") ? csharpType.Substring(0, csharpType.Length - 1) : csharpType;
        return baseType switch
        {
            "int" => "Int32",
            "long" => "Int64",
            "short" => "Int16",
            "bool" => "Boolean",
            "decimal" => "Decimal",
            "double" => "Double",
            "float" => "Single",
            "string" => "String",
            "System.DateTime" => "DateTime",
            "System.TimeSpan" => "Time",
            "System.Guid" => "Guid",
            "byte[]" => "Binary",
            _ => null
        };
    }

    private static bool IsBoundColumnNullable(ParameterRef param, QueryModel query, DatabaseSchema? schema)
    {
        if (schema == null || string.IsNullOrEmpty(param.BoundColumnName) || query.TargetTable == null)
            return false;
        return schema.Tables.TryGetValue(query.TargetTable, out var tableSchema)
            && tableSchema.Columns.TryGetValue(param.BoundColumnName, out var col)
            && col.IsNullable;
    }

    internal static string InferCrudParameterType(ParameterRef param, QueryModel query, DatabaseSchema? schema, Directives.DirectiveModel? directives = null)
    {
        // Check @params directive first
        if (directives?.ExplicitParams != null)
        {
            foreach (var ep in directives.ExplicitParams)
            {
                if (string.Equals(ep.Name, param.Name, StringComparison.OrdinalIgnoreCase))
                    return ep.CSharpType;
            }
        }

        if (!string.IsNullOrEmpty(param.BoundColumnName) && schema != null)
        {
            // For CRUD, the target table is the primary table
            string? targetTable = query.TargetTable;
            if (targetTable != null && schema.Tables.TryGetValue(targetTable, out var tableSchema))
            {
                if (tableSchema.Columns.TryGetValue(param.BoundColumnName, out var colSchema))
                {
                    return DialectMapper.MapColumnToCSharp(colSchema);
                }
            }

            // Fallback: try alias-based resolution
            var resolved = ResolveColumnType(param.BoundTableAlias, param.BoundColumnName, query, schema);
            if (resolved != null)
                return resolved;
        }

        return "object";
    }

