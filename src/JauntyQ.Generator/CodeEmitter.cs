    /// <summary>
    /// Dialect-native upsert keyed on the primary key. Bypasses the SQL
    /// parser deliberately: MERGE / ON CONFLICT / ON DUPLICATE KEY are
    /// outside the minimal grammar, and the SQL is correct by construction
    /// from the schema snapshot.
    /// </summary>
    public static string EmitUpsert(string entityName, TableSchema tableSchema, string dialect)
    {
        // Rowversion tokens are database-assigned: excluded from the upsert
        // column set entirely. Upsert is documented last-writer-wins.
        var columns = tableSchema.Columns.Values.Where(c => !c.IsRowVersion).ToList();
        var pkCols = columns.FindAll(c => c.IsPrimaryKey);
        var setCols = columns.FindAll(c => !c.IsPrimaryKey);

        string colList = string.Join(", ", columns.Select(c => c.Name));
        string paramList = string.Join(", ", columns.Select(c => $"@{c.Name}"));

        string sql;
        switch (dialect)
        {
            case "sqlserver":
            {
                string srcSelect = string.Join(", ", columns.Select(c => $"@{c.Name} as {c.Name}"));
                string onClause = string.Join(" and ", pkCols.Select(c => $"target.{c.Name} = src.{c.Name}"));
                string updateSet = string.Join(", ", setCols.Select(c => $"{c.Name} = src.{c.Name}"));
                string insertVals = string.Join(", ", columns.Select(c => $"src.{c.Name}"));
                sql = $"merge into {tableSchema.Name} with (holdlock) as target\n" +
                      $"using (select {srcSelect}) as src\n" +
                      $"on {onClause}\n" +
                      $"when matched then update set {updateSet}\n" +
                      $"when not matched then insert ({colList}) values ({insertVals});";
                break;
            }
            case "postgres":
            case "sqlite":
            {
                string conflictCols = string.Join(", ", pkCols.Select(c => c.Name));
                string updateSet = string.Join(", ", setCols.Select(c => $"{c.Name} = excluded.{c.Name}"));
                sql = $"insert into {tableSchema.Name} ({colList})\nvalues ({paramList})\n" +
                      $"on conflict ({conflictCols}) do update set {updateSet}";
                break;
            }
            case "mysql":
            {
                // VALUES(col) works on both MySQL and MariaDB (the 8.0.20+
                // alias form is not MariaDB-compatible).
                string updateSet = string.Join(", ", setCols.Select(c => $"{c.Name} = values({c.Name})"));
                sql = $"insert into {tableSchema.Name} ({colList})\nvalues ({paramList})\n" +
                      $"on duplicate key update {updateSet}";
                break;
            }
            default:
                throw new System.InvalidOperationException($"Upsert synthesis requires a known dialect (got '{dialect}').");
        }

        var paramInfos = new System.Collections.Generic.List<EmittedParam>();
        foreach (var col in columns)
        {
            paramInfos.Add(CreateEmittedParam(col.Name, DialectMapper.MapColumnToCSharp(col), col.IsNullable, col, tableSchema.Name, isWriteTarget: true));
        }

        var stub = new QueryModel { Name = "Upsert" };

        var sb = new System.Text.StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace JauntyQ.Generated");
        sb.AppendLine("{");
        sb.AppendLine($"    public partial class {entityName}");
        sb.AppendLine("    {");
        EmitCrudMethodBody(sb, stub, sql, paramInfos, "_conn", isStatic: false, isAsync: false, dialect: dialect);
        sb.AppendLine();
        EmitCrudMethodBody(sb, stub, sql, paramInfos, "conn", isStatic: true, isAsync: false, dialect: dialect);
        sb.AppendLine();
        EmitCrudMethodBody(sb, stub, sql, paramInfos, "_conn", isStatic: false, isAsync: true, dialect: dialect);
        sb.AppendLine();
        EmitCrudMethodBody(sb, stub, sql, paramInfos, "conn", isStatic: true, isAsync: true, dialect: dialect);
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// POCO-taking overloads for the synthetic write methods:
    /// Update(product), Insert(shipper) (with identity write-back),
    /// Delete(product), Upsert(customer). Emitted only when the scalar
    /// method is the synthetic one - a user override owns its own signature.
    /// </summary>
    public static string EmitPocoOverloads(
        string entityName,
        string rowType,
        TableSchema tableSchema,
        string dialect,
        bool hasInsert,
        bool hasUpdate,
        bool hasDelete,
        bool hasUpsert)
    {
        var columns = new System.Collections.Generic.List<ColumnSchema>(tableSchema.Columns.Values);
        var versionCols = columns.FindAll(c => c.IsRowVersion);
        var pkCols = columns.FindAll(c => c.IsPrimaryKey);
        var setCols = columns.FindAll(c => !c.IsPrimaryKey && !c.IsRowVersion);
        var insertCols = columns.FindAll(c => !c.IsIdentity && !c.IsRowVersion);
        ColumnSchema? identityCol = null;
        foreach (var c in columns)
        {
            if (c.IsIdentity) { identityCol = identityCol == null ? c : null; if (identityCol == null) break; }
        }
        bool insertReturnsId = identityCol != null && !string.IsNullOrEmpty(dialect);

        string Args(System.Collections.Generic.List<ColumnSchema> cols)
            => string.Join(", ", cols.Select(c => $"row.{IdentifierGuard.Escape(DialectMapper.ToPascalCase(c.Name))}"));

        var sb = new System.Text.StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace JauntyQ.Generated");
        sb.AppendLine("{");
        sb.AppendLine($"    public partial class {entityName}");
        sb.AppendLine("    {");

        void Forward(string method, System.Collections.Generic.List<ColumnSchema> cols)
        {
            string args = Args(cols);
            sb.AppendLine($"        public int {method}({rowType} row) => {method}({args});");
            sb.AppendLine($"        public static int {method}(System.Data.Common.DbConnection conn, {rowType} row) => {method}(conn, {args});");
            sb.AppendLine($"        public System.Threading.Tasks.Task<int> {method}Async({rowType} row, System.Threading.CancellationToken cancellationToken = default) => {method}Async({args}, cancellationToken);");
            sb.AppendLine($"        public static System.Threading.Tasks.Task<int> {method}Async(System.Data.Common.DbConnection conn, {rowType} row, System.Threading.CancellationToken cancellationToken = default) => {method}Async(conn, {args}, cancellationToken);");
            sb.AppendLine();
        }

        if (hasInsert && insertCols.Count > 0)
        {
            if (insertReturnsId)
            {
                string idProp = IdentifierGuard.Escape(DialectMapper.ToPascalCase(identityCol!.Name));
                string idType = DialectMapper.MapDbTypeToCSharp(identityCol.DbType, isNullable: false);
                string args = Args(insertCols);
                sb.AppendLine($"        /// <summary>Inserts the row and writes the database-assigned {idProp} back onto it.</summary>");
                sb.AppendLine($"        public {idType} Insert({rowType} row)");
                sb.AppendLine("        {");
                sb.AppendLine($"            {idType} id = Insert({args});");
                sb.AppendLine($"            row.{idProp} = id;");
                sb.AppendLine("            return id;");
                sb.AppendLine("        }");
                sb.AppendLine();
                sb.AppendLine($"        public static {idType} Insert(System.Data.Common.DbConnection conn, {rowType} row)");
                sb.AppendLine("        {");
                sb.AppendLine($"            {idType} id = Insert(conn, {args});");
                sb.AppendLine($"            row.{idProp} = id;");
                sb.AppendLine("            return id;");
                sb.AppendLine("        }");
                sb.AppendLine();
                sb.AppendLine($"        public async System.Threading.Tasks.Task<{idType}> InsertAsync({rowType} row, System.Threading.CancellationToken cancellationToken = default)");
                sb.AppendLine("        {");
                sb.AppendLine($"            {idType} id = await InsertAsync({args}, cancellationToken).ConfigureAwait(false);");
                sb.AppendLine($"            row.{idProp} = id;");
                sb.AppendLine("            return id;");
                sb.AppendLine("        }");
                sb.AppendLine();
                sb.AppendLine($"        public static async System.Threading.Tasks.Task<{idType}> InsertAsync(System.Data.Common.DbConnection conn, {rowType} row, System.Threading.CancellationToken cancellationToken = default)");
                sb.AppendLine("        {");
                sb.AppendLine($"            {idType} id = await InsertAsync(conn, {args}, cancellationToken).ConfigureAwait(false);");
                sb.AppendLine($"            row.{idProp} = id;");
                sb.AppendLine("            return id;");
                sb.AppendLine("        }");
                sb.AppendLine();
            }
            else
            {
                Forward("Insert", insertCols);
            }
        }

        if (hasUpdate && setCols.Count > 0 && pkCols.Count > 0)
        {
            // scalar Update parameter order: SET columns then PK columns
            var updateArgsCols = new System.Collections.Generic.List<ColumnSchema>(setCols);
            updateArgsCols.AddRange(pkCols);
            updateArgsCols.AddRange(versionCols);
            Forward("Update", updateArgsCols);
        }

        if (hasDelete && pkCols.Count > 0)
        {
            var deleteArgsCols = new System.Collections.Generic.List<ColumnSchema>(pkCols);
            deleteArgsCols.AddRange(versionCols);
            Forward("Delete", deleteArgsCols);
        }

        if (hasUpsert)
        {
            Forward("Upsert", columns.FindAll(c => !c.IsRowVersion));
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

